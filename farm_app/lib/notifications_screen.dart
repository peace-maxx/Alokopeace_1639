// ---------------------------------------------------------------------------
// SCREEN
// ---------------------------------------------------------------------------
class NotificationsScreen extends StatelessWidget {
  const NotificationsScreen({super.key});

  static const _tabs = ['All', 'Health', 'Sales', 'System'];

  @override
  Widget build(BuildContext context) {
    return DefaultTabController(
      length: _tabs.length,
      child: Scaffold(
        appBar: AppBar(
          title: const Text('Notifications'),
          actions: [
            IconButton(
              tooltip: 'Mark all as read',
              icon: const Icon(Icons.done_all),
              onPressed: notificationStore.markAllRead,
            ),
          ],
          bottom: TabBar(
            labelColor: Colors.white,
            unselectedLabelColor: Colors.white70,
            indicatorColor: Colors.white,
            tabs: _tabs.map((t) => Tab(text: t)).toList(),
          ),
        ),
        body: ListenableBuilder(
          listenable: notificationStore,
          builder: (context, _) {
            return TabBarView(
              children: _tabs
                  .map((t) => _NotificationList(category: t))
                  .toList(),
            );
          },
        ),
      ),
    );
  }
}

class _NotificationList extends StatelessWidget {
  final String category;
  const _NotificationList({required this.category});

  @override
  Widget build(BuildContext context) {
    final items = notificationStore.items
        .where((n) => category == 'All' || n.category == category)
        .toList();

    if (items.isEmpty) {
      return const Center(child: Text('No notifications'));
    }

    return ListView.builder(
      padding: const EdgeInsets.all(16),
      itemCount: items.length,
      itemBuilder: (_, i) => _NotificationTile(item: items[i]),
    );
  }
}

class _NotificationTile extends StatelessWidget {
  final AppNotification item;
  const _NotificationTile({required this.item});

  @override
  Widget build(BuildContext context) {
    return Card(
      color: item.read ? Colors.white : const Color(0xFFF0F8F1),
      elevation: 1,
      margin: const EdgeInsets.only(bottom: 10),
      child: InkWell(
        borderRadius: BorderRadius.circular(12),
        onTap: () => notificationStore.markRead(item),
        child: Padding(
          padding: const EdgeInsets.all(12),
          child: Row(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              CircleAvatar(
                radius: 22,
                backgroundColor: item.color.withValues(alpha: 0.15),
                child: Icon(item.icon, color: item.color),
              ),
              const SizedBox(width: 12),
              Expanded(
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Text(
                      item.title,
                      style: TextStyle(
                        fontSize: 14,
                        fontWeight:
                            item.read ? FontWeight.w500 : FontWeight.bold,
                      ),
                    ),
                    const SizedBox(height: 2),
                    Text(item.message,
                        style: const TextStyle(
                            fontSize: 12, color: Colors.black87)),
                    const SizedBox(height: 4),
                    Text(item.time,
                        style: const TextStyle(
                            fontSize: 11, color: Colors.black45)),
                  ],
                ),
              ),
              if (!item.read)
                Container(
                  margin: const EdgeInsets.only(top: 6),
                  width: 9,
                  height: 9,
                  decoration: const BoxDecoration(
                    color: AppColors.green,
                    shape: BoxShape.circle,
                  ),
                ),
            ],
          ),
        ),
      ),
    );
  }
}