class AppNotification {
  final String title;
  final String message;
  final String category; // Health, Sales or System
  final String time;
  final IconData icon;
  final Color color;
  bool read;

  AppNotification({
    required this.title,
    required this.message,
    required this.category,
    required this.time,
    required this.icon,
    required this.color,
    this.read = false,
  });
}

